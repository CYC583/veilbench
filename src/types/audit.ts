/**
 * Locked TypeScript contract for Document Intake, Triage, Redline Negotiation & Translation.
 * Shared across Antigravity (UI/Firebase) and Codex (src/core/*).
 */

import type { ActualInferenceSource } from './hybrid';
import type { ImageRedactionRegion } from './privacy';

export type SupportedLocale = 'en' | 'zh-TW';

export type DocumentCategory = 'contract' | 'medical' | 'financial' | 'custom';

export interface WorkbenchDocument {
  id: string;
  title: string;
  category: DocumentCategory;
  rawText: string;
  sanitizedText: string;
  /** Optional image data URL (JPEG/PNG) for multimodal documents */
  rawImageDataUrl?: string;
  /** Pixel-burned sanitized PNG data URL generated by canvasRedactor */
  redactedImageDataUrl?: string;
  imageRegions?: ImageRedactionRegion[];
  /** User-uploaded images are blocked by Layer 3 until a human confirms the burned preview. */
  requiresImageReview?: boolean;
  imageReviewed?: boolean;
  createdAt: string;
}

export type RiskSeverity = 'high' | 'medium' | 'low';

export interface TriageFlag {
  id: string;
  title: string;
  severity: RiskSeverity;
  plainSummary: string;
  excerpt: string;
}

export interface TriageResult {
  overallRisk: RiskSeverity;
  headline: string;
  flags: TriageFlag[];
  inferenceSource: ActualInferenceSource;
  generatedAt: string;
}

export interface ContradictionFinding {
  id: string;
  docATitle: string;
  docBTitle: string;
  severity: RiskSeverity;
  description: string;
  recommendation: string;
}

export interface RedlineClause {
  id: string;
  clauseTitle: string;
  severity: RiskSeverity;
  originalExcerpt: string;
  proposedRevision: string;
  rationale: string;
}

export interface NegotiationPlaybook {
  executiveSummary: string;
  counterpartyPushback: Array<{
    objection: string;
    recommendedResponse: string;
  }>;
  readyToSendEmailSanitized: string;
}

export interface DeepAuditResult {
  contradictions: ContradictionFinding[];
  redlines: RedlineClause[];
  playbook: NegotiationPlaybook;
  inferenceSource: ActualInferenceSource;
  generatedAt: string;
  /** Stage 4 halves that did not complete (split analysis / playbook calls). */
  incompleteParts?: Array<'analysis' | 'playbook'>;
  /** Halves filled from the recorded demo cache after a live failure (always badged in the UI). */
  cachedParts?: Array<'analysis' | 'playbook'>;
  cacheInfo?: { recordedAt: string; analysisModel: string; playbookModel: string };
}

export interface ChatTurn {
  id: string;
  role: 'user' | 'assistant';
  sanitizedContent: string;
  rehydratedContent: string;
  inferenceSource?: ActualInferenceSource;
  timestamp: string;
}

/**
 * Strictly sanitized document shape persisted to Cloud Firestore.
 * NEVER contains rawText, rawImageDataUrl, or VaultMap.
 */
export interface SanitizedFirestoreSession {
  id: string;
  uid: string;
  title: string;
  category: DocumentCategory;
  documentCount: number;
  sanitizedExcerpts: Array<{ documentId: string; title: string; sanitizedText: string }>;
  zeroLeakProofHash: string;
  triage?: TriageResult;
  deepAudit?: DeepAuditResult;
  updatedAt: string;
}
